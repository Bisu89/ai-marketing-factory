"""Voice lines (edge-tts, 3 voices) + timeline -> remotion/src/pk-ep01/data.ts, from content-prompts/packed_light/ep01_open_test.csv.
Voice files already in remotion/public/pk-ep01/voice are reused; delete them to re-synthesize."""
import asyncio, csv, json, os, subprocess
from pathlib import Path
import edge_tts

ROOT = str(Path(__file__).resolve().parents[2])
CSV = ROOT + "/content-prompts/packed_light/ep01_open_test.csv"
PUB = ROOT + "/remotion/public/pk-ep01"
DATA = ROOT + "/remotion/src/pk-ep01/data.ts"
FPS = 30

VOICES = {
    "N": ("en-US-EricNeural", "-4%", "+0Hz"),
    "D": ("en-US-ChristopherNeural", "-6%", "-2Hz"),
    "S": ("en-US-AnaNeural", "+4%", "+3Hz"),
}
LINES = {
    1: [("N", "First weekend of the season. Same campground, same site.")],
    2: [("N", "Fires are allowed, in rings only. Dad reads the board twice anyway.")],
    3: [("N", "Thirty steps from the car.")],
    5: [("S", "I'm doing the fire."), ("D", "Good. The stove's right there if you want it.")],
    6: [("S", "I won't."), ("D", "Then it'll just look nice on the table.")],
    8: [("N", "It rained most of last week. He knows that. He's in a hurry anyway.")],
    9: [("N", "Big wood, big fire. That's the plan.")],
    11: [("S", "It's just smoking."), ("D", "It is.")],
    12: [("D", "Try looking at the wood instead of the fourth match.")],
}
SFX = {
    1: [(0.7, "bird1", 0.5), (2.6, "bird2", 0.4)],
    2: [(0.2, "steps_gravel", 0.5), (4.2, "bird2", 0.3)],
    3: [(0.4, "rope", 0.6), (1.2, "tarp_flap", 0.6)],
    4: [(0.5, "clink", 0.6), (0.9, "slosh", 0.7)],
    5: [(1.0, "bird1", 0.3)],
    7: [(0.2, "tin_slide", 0.7)],
    8: [(0.3, "steps_leaves", 0.6), (3.4, "twig_snap", 0.5), (4.6, "branch_clatter", 0.5)],
    9: [(0.3, "branch_clatter", 0.5)],
    10: [(0.9, "match_strike", 0.8)],
    11: [(0.2, "smoke_hiss", 0.6)],
    12: [(0.1, "wood_snap", 0.9)],
}
LEAD, GAP, TAIL, MIN_SILENT = 0.3, 0.22, 0.35, 2.6


def dur(path):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path])
    return float(out.decode().strip())


async def synth(text, who, path):
    voice, rate, pitch = VOICES[who]
    for attempt in range(5):
        try:
            await edge_tts.Communicate(text, voice, rate=rate, pitch=pitch).save(path)
            if os.path.getsize(path) > 1000:
                return
        except Exception as e:  # free endpoint is flaky
            print("retry", attempt, e)
        await asyncio.sleep(1.5 * (attempt + 1))
    raise RuntimeError("TTS failed: " + text)


async def main():
    rows = [r for r in csv.reader(open(CSV, encoding="utf-8-sig", newline=""))][2:]
    os.makedirs(PUB + "/voice", exist_ok=True)
    jobs, files = [], {}
    for n, lines in LINES.items():
        for k, (who, text) in enumerate(lines):
            p = PUB + f"/voice/L{n:02d}_{k}.mp3"
            files[(n, k)] = p
            if not (os.path.exists(p) and os.path.getsize(p) > 1000):
                jobs.append(synth(text, who, p))
    await asyncio.gather(*jobs)

    t = 0.0
    shots, lines_out, sfx_out = [], [], []
    for i, r in enumerate(rows, 1):
        motion, fx = r[5], r[6]
        ls = LINES.get(i, [])
        cur = LEAD
        for k, (who, text) in enumerate(ls):
            d = dur(files[(i, k)])
            lines_out.append(dict(from_=t + cur, to=t + cur + d, who=who, text=text, file=f"pk-ep01/voice/L{i:02d}_{k}.mp3"))
            cur += d + GAP
        shot_d = (cur - GAP + TAIL) if ls else MIN_SILENT
        for off, name, vol in SFX.get(i, []):
            shot_d = max(shot_d, off + 0.8)
            sfx_out.append(dict(frame=round((t + off) * FPS), name=name, vol=vol))
        shots.append(dict(n=i, image=f"pk-ep01/images/scene{i:02d}.png", motion=motion, fx=fx, from_=round(t * FPS), dur=round(shot_d * FPS)))
        t += shot_d
    total = round((t + 0.8) * FPS)

    def ts(o):
        return json.dumps(o, ensure_ascii=False).replace('"from_"', '"from"')

    with open(DATA, "w", encoding="utf-8") as f:
        f.write("// generated by the Packed Light test-cut builder; edit the generator, not this file\n")
        f.write(f"export const FPS = {FPS};\n")
        f.write(f"export const DURATION = {total};\n")
        f.write("export type Shot = { n: number; image: string; motion: string; fx: string; from: number; dur: number };\n")
        f.write(f"export const SHOTS: Shot[] = {ts(shots)};\n")
        f.write("export type Line = { from: number; to: number; who: string; text: string; file: string };\n")
        ls_frames = [dict(l, from_=round(l["from_"] * FPS), to=round(l["to"] * FPS)) for l in lines_out]
        for l in ls_frames:
            l.pop("to_", None)
        f.write(f"export const LINES: Line[] = {ts([{'from_': l['from_'], 'to': l['to'], 'who': l['who'], 'text': l['text'], 'file': l['file']} for l in ls_frames])};\n")
        f.write("export type Sfx = { frame: number; name: string; vol: number };\n")
        f.write(f"export const SFX: Sfx[] = {ts(sfx_out)};\n")
    print("shots", len(shots), "total s", round(t + 0.8, 1), "frames", total)
    for s in shots:
        print(s["n"], s["from_"] / FPS, s["dur"] / FPS)


os.makedirs(os.path.dirname(DATA), exist_ok=True)
asyncio.run(main())
